#!/usr/bin/env python3
"""Compute descriptive statistics for the curated project dataset.

Fast path: join the final repo list with the local GHS snapshot
(data/misc/filtered_file.csv). No GitHub API calls required.

Metrics:
  - stars   -> stargazers (GHS)
  - forks   -> forks (GHS)
  - commits -> commits (GHS, total repository commits at crawl time)
  - size_kb -> size (GHS/GitHub repository size in kilobytes)

Note: GHS does not provide per-repository line-of-code counts. We report
GitHub repository size (KB), which is the standard scale proxy in GHS-based
MSR studies when LOC is unavailable at corpus scale.
"""

from __future__ import annotations

import argparse
import csv
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_REPOS = ROOT / "data/repos/repos_analysis.csv"
DEFAULT_GHS = ROOT / "data/misc/filtered_file.csv"
DEFAULT_OUT_DIR = ROOT / "thesis_reclassification"


def load_repo_list(path: Path) -> list[str]:
    repos: list[str] = []
    with path.open(newline="", encoding="utf-8") as f:
        if path.suffix == ".csv":
            reader = csv.DictReader(f)
            if "repo" not in (reader.fieldnames or []):
                raise ValueError(f"CSV {path} must contain a 'repo' column")
            for row in reader:
                repo = (row.get("repo") or "").strip()
                if repo:
                    repos.append(repo)
        else:
            for line in f:
                repo = line.strip()
                if repo:
                    repos.append(repo)
    # preserve order, drop duplicates
    seen: set[str] = set()
    ordered: list[str] = []
    for repo in repos:
        if repo not in seen:
            seen.add(repo)
            ordered.append(repo)
    return ordered


def load_ghs_metadata(path: Path) -> dict[str, dict[str, str]]:
    meta: dict[str, dict[str, str]] = {}
    with path.open(newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            name = (row.get("name") or "").strip()
            if name:
                meta[name] = row
    return meta


def as_float(value: str | None) -> float | None:
    if value is None:
        return None
    value = value.strip()
    if not value:
        return None
    try:
        return float(value)
    except ValueError:
        return None


def summarize(values: list[float]) -> dict[str, float | int]:
    if not values:
        raise ValueError("No values to summarize")
    values_sorted = sorted(values)
    n = len(values_sorted)
    return {
        "n": n,
        "min": values_sorted[0],
        "max": values_sorted[-1],
        "mean": statistics.fmean(values_sorted),
        "median": statistics.median(values_sorted),
    }


def fmt_num(value: float, decimals: int = 0) -> str:
    if decimals == 0:
        return f"{round(value):,}"
    return f"{value:,.{decimals}f}"


def write_latex_table(stats: dict[str, dict[str, float | int]], out_path: Path, n_repos: int) -> None:
    rows = [
        ("Stars", "stars"),
        ("Forks", "forks"),
        ("Commits", "commits"),
        ("Repository size (KB)", "size_kb"),
    ]
    n_fmt = f"{n_repos:,}".replace(",", "{,}")
    lines = [
        "% Auto-generated by scripts/compute_dataset_descriptive_stats.py",
        "\\begin{table}[t]",
        "    \\centering",
        "    \\small",
        "    \\setlength{\\tabcolsep}{5pt}",
        "    \\caption{\\small",
        f"    Descriptive statistics of the curated dataset (\\\\datasetstatsn{{}} projects).",
        "    All values are taken directly from the original GHS repository metadata \\citep{dabic2021sampling}: stars (\\texttt{stargazers}), forks (\\texttt{forks}), total commits (\\texttt{commits}), and GitHub repository size in kilobytes (\\texttt{size}).",
        "    For each field, we report the minimum, median, mean, and maximum across the curated projects.",
        "    }",
        "    \\label{tab:dataset_stats}",
        "    \\begin{tabular}{lrrrrr}",
        "        \\toprule",
        "        \\textbf{Metric} & \\textbf{Min} & \\textbf{Median} & \\textbf{Mean} & \\textbf{Max} & \\textbf{$n$} \\\\",
        "        \\midrule",
    ]
    for label, key in rows:
        s = stats[key]
        lines.append(
            f"        {label:<22} & {fmt_num(s['min'])} & {fmt_num(s['median'])} & {fmt_num(s['mean'])} & "
            f"{fmt_num(s['max'])} & {n_fmt} \\\\"
        )
    lines.extend(
        [
            "        \\bottomrule",
            "    \\end{tabular}",
            "\\end{table}",
        ]
    )
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repos", type=Path, default=DEFAULT_REPOS)
    parser.add_argument("--ghs", type=Path, default=DEFAULT_GHS)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args()

    repos = load_repo_list(args.repos)
    ghs = load_ghs_metadata(args.ghs)

    matched_rows: list[dict[str, str]] = []
    missing: list[str] = []
    for repo in repos:
        row = ghs.get(repo)
        if row is None:
            missing.append(repo)
            continue
        matched_rows.append(row)

    metrics = {
        "stars": [],
        "forks": [],
        "commits": [],
        "size_kb": [],
    }
    for row in matched_rows:
        for key, col in [
            ("stars", "stargazers"),
            ("forks", "forks"),
            ("commits", "commits"),
            ("size_kb", "size"),
        ]:
            value = as_float(row.get(col))
            if value is not None:
                metrics[key].append(value)

    stats = {key: summarize(values) for key, values in metrics.items()}

    out_dir = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    summary = {
        "repo_list": str(args.repos),
        "ghs_snapshot": str(args.ghs),
        "requested_repos": len(repos),
        "matched_repos": len(matched_rows),
        "missing_repos": len(missing),
        "missing_sample": missing[:20],
        "statistics": stats,
        "notes": {
            "commits": "Total repository commits from GHS at crawl time",
            "size_kb": "GitHub repository size in kilobytes from GHS; used as project-scale proxy",
        },
    }

    json_path = out_dir / "dataset_descriptive_stats.json"
    json_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")

    tex_path = out_dir / "dataset_stats.tex"
    write_latex_table(stats, tex_path, len(matched_rows))

    print(f"Requested repos: {len(repos):,}")
    print(f"Matched in GHS:  {len(matched_rows):,}")
    print(f"Missing in GHS:  {len(missing):,}")
    if missing:
        print("Missing sample:", ", ".join(missing[:10]))
    print()
    for key in ["stars", "forks", "commits", "size_kb"]:
        s = stats[key]
        print(
            f"{key:8s}  min={fmt_num(s['min']):>10}  median={fmt_num(s['median']):>10}  "
            f"mean={fmt_num(s['mean']):>10}  max={fmt_num(s['max']):>10}"
        )
    print()
    print(f"Wrote {json_path}")
    print(f"Wrote {tex_path}")


if __name__ == "__main__":
    main()
